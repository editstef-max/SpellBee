"""Builds words.js: the accepted word list and the list of playable puzzles.

Usage:
    python build_words.py <path to node_modules/wordlist-english> <output words.js>

Word source: the `wordlist-english` npm package (SCOWL lists, British spellings).
Requires the `wordfreq` package (pip install wordfreq) to filter out obscure words.

How it works:
  * A word is accepted if it is in the British English list (SCOWL "english" +
    "british" lists, size 50 and below), is lower case, 4+ letters, contains no "s",
    uses at most 7 different letters and is common enough (wordfreq Zipf score).
    4-letter words need a higher score, since that is where most junk lives.
  * A puzzle is a set of 7 letters taken from a common "pangram" word, plus a centre
    letter. We keep only centre choices that give a fun number of answers.
"""
import json
import os
import random
import sys

from wordfreq import zipf_frequency

SCOWL_LEVELS = (10, 20, 35, 40, 50)
MIN_ZIPF_SHORT = 3.0   # 4-letter words
MIN_ZIPF = 1.5         # longer words
MIN_ZIPF_PANGRAM = 3.0 # the word a puzzle is built from should be well known
MIN_ANSWERS, MAX_ANSWERS = 18, 75
MAX_SCORE = 450

# Words that are valid but not wanted in a family-friendly game. Extend as needed.
BLOCKLIST = set("""
fuck fucking fucker fucked motherfucker cunt twat wank wanker wanking bollock bollocking
nigger nigga faggot fagging dyke kike chink gook coon wetback tranny retard retarded
cock cocking dick dickhead prick pussy bitch bitching bitchy whore titty boob boobie
piss pissing pissed crap crapping turd rape raping raped rapist porn porno horny
""".split())


def score(word):
    if len(word) == 4:
        return 1
    return len(word) + (7 if len(set(word)) == 7 else 0)


def main(dict_dir, out_path):
    raw = set()
    for region in ("english", "british"):
        for level in SCOWL_LEVELS:
            raw |= set(json.load(open(os.path.join(dict_dir, f"{region}-words-{level}.json"))))
    words = []
    for w in raw:
        if len(w) < 4 or not (w.isascii() and w.isalpha() and w.islower()):
            continue
        if "s" in w or len(set(w)) > 7 or w in BLOCKLIST:
            continue
        z = zipf_frequency(w, "en")
        if z < (MIN_ZIPF_SHORT if len(w) == 4 else MIN_ZIPF):
            continue
        words.append(w)
    words.sort()

    letter_sets = sorted({"".join(sorted(set(w))) for w in words
                          if len(set(w)) == 7 and zipf_frequency(w, "en") >= MIN_ZIPF_PANGRAM})

    masks = {}
    for w in words:
        masks.setdefault(frozenset(w), []).append(w)

    puzzles = []
    rng = random.Random(2026)
    for letters in letter_sets:
        ls = set(letters)
        pool = [w for key, ws in masks.items() if key <= ls for w in ws]
        options = []
        for centre in letters:
            ans = [w for w in pool if centre in w]
            total = sum(score(w) for w in ans)
            if MIN_ANSWERS <= len(ans) <= MAX_ANSWERS and total <= MAX_SCORE:
                options.append(centre)
        if options:
            centre = rng.choice(options)
            outer = [c for c in letters if c != centre]
            puzzles.append(centre + "".join(outer))

    rng.shuffle(puzzles)
    with open(out_path, "w") as f:
        f.write("// Generated by tools/build_words.py. Do not edit by hand.\n")
        f.write("// Each puzzle is the centre letter followed by the 6 outer letters.\n")
        f.write("const PUZZLES = " + json.dumps(puzzles) + ";\n")
        f.write("const WORDS = " + json.dumps(" ".join(words)) + '.split(" ");\n')
    print(f"{len(words)} words, {len(letter_sets)} letter sets, {len(puzzles)} puzzles -> {out_path}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
